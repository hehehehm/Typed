#!/usr/bin/env python3
"""Tag frequent Russian words for the missing-space fixer (crates/core/src/split.rs).

Writes crates/core/data/ru_split_tags.txt: frequent words (all ranked words of 4+ letters)
that must not be the second half of a split, with a tag:
  g  place names (`москвы`): fine after a preposition (`до москвы`);
  n  proper names, organisations, words without a dictionary parse (`майли`, `аллена`): unknown
     names glued like `камаро` → `к амаро` are the main false positives;
  v  verb forms (`рулить`, `долбал`): `по`/`за`/`про`… are also verb prefixes
     (`порулить`, `задолбал`), so these halves count only after `не` (`не знаю`).
Tags come from the OpenCorpora dictionary via pymorphy3 (CC-BY-SA 3.0).
Usage: <venv>/bin/python split_tags.py <repo root>
"""
import sys, pymorphy3
REPO = sys.argv[1]
m = pymorphy3.MorphAnalyzer()
words = []
for i, l in enumerate(open(f'{REPO}/crates/core/data/ru.txt', encoding='utf-8')):
    w = l.strip()
    if i >= 40000: break
    if len(w) >= 4: words.append(w)
for l in open(f'{REPO}/crates/core/data/ru_extra.txt', encoding='utf-8'):
    w = l.strip().lower().replace('ё', 'е')
    if w and not w.startswith('#') and len(w) >= 4 and w not in words: words.append(w)
NAME = {'Name', 'Surn', 'Patr', 'Geox', 'Orgn', 'Trad', 'Init'}
VERB = {'VERB', 'INFN', 'GRND', 'PRTF', 'PRTS'}
out = []
for w in words:
    ps = [p for p in m.parse(w) if p.is_known]
    if not ps:
        out.append(('n', w)); continue
    common = [p for p in ps if not (NAME & p.tag.grammemes)]
    if not common:
        geo = all('Geox' in p.tag.grammemes and not ({'Name', 'Surn', 'Patr'} & p.tag.grammemes) for p in ps)
        out.append(('g' if geo else 'n', w)); continue
    if all(p.tag.POS in VERB for p in common):
        out.append(('v', w))
with open(f'{REPO}/crates/core/data/ru_split_tags.txt', 'w', encoding='utf-8') as f:
    f.write('# Generated by tools/brands/split_tags.py from OpenCorpora tags (pymorphy3), CC-BY-SA 3.0.\n'
            '# n = name / no parse (never the second half of a split), g = place (after prepositions only),\n'
            '# v = verb form (only after «не»).\n')
    for t, w in out: f.write(f'{t} {w}\n')
print(len(words), 'words;', sum(t == 'n' for t, _ in out), 'names,', sum(t == 'g' for t, _ in out), 'places,', sum(t == 'v' for t, _ in out), 'verbs')
