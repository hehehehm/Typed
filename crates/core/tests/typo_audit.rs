fn ok_words(list: &str) -> Vec<&str> {
    list.split_whitespace().collect()
}

#[test]
fn audit() {
    let mut fp = Vec::new();
    let ru = ok_words(RU_OK);
    let en = ok_words(EN_OK);
    for w in &ru {
        if let Some(f) = typo::suggest(w, Lang::Ru) {
            fp.push(format!("{w} -> {f}"));
        }
    }
    for w in &en {
        if let Some(f) = typo::suggest(w, Lang::En) {
            fp.push(format!("{w} -> {f}"));
        }
    }
    let mut miss = Vec::new();
    for (t, e) in RU_FIX.iter().map(|p| (p, Lang::Ru)).chain(EN_FIX.iter().map(|p| (p, Lang::En))).map(|(p, l)| ((p.0, l), p.1)) {
        let got = typo::suggest(t.0, t.1);
        if got.as_deref() != Some(e) {
            miss.push(format!("{} -> {:?} (want {e})", t.0, got));
        }
    }
    eprintln!("correct words: {} ru + {} en, false positives: {}", ru.len(), en.len(), fp.len());
    for f in &fp { eprintln!("  FP {f}"); }
    eprintln!("typos: {}, wrong/missed: {}", RU_FIX.len() + EN_FIX.len(), miss.len());
    for m in &miss { eprintln!("  MISS {m}"); }
    assert!(fp.is_empty(), "false positives: {fp:?}");
    assert!(miss.is_empty(), "missed: {miss:?}");
}
